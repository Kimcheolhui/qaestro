"""Tests for official GitHub review output surface."""

from __future__ import annotations

from src.adapters.connectors.github import CommentResult, ReviewCommentInput, ReviewResult
from src.adapters.renderers import PRCommentPayload, PRReviewComment, PRReviewPayload
from src.runtime.orchestrator import ToolRuntimePROutputPoster
from src.runtime.stages import WorkflowStage
from src.runtime.tools import ToolAuditEntry, ToolCall, ToolResult


class RecordingRuntime:
    def __init__(self, *, current_head_sha: str = "abc123", existing_reviews: tuple[ReviewResult, ...] = ()) -> None:
        self.calls: list[ToolCall] = []
        self.current_head_sha = current_head_sha
        self.existing_reviews = existing_reviews
        self.outputs = {
            "github.pr.comment.create_or_update": CommentResult(
                id=99,
                html_url="https://github.com/octocat/hello-world/pull/7#issuecomment-99",
                body="summary body",
            ),
            "github.pr.review.create": ReviewResult(
                id=42,
                html_url="https://github.com/octocat/hello-world/pull/7#pullrequestreview-42",
                state="COMMENTED",
                body="review body",
                commit_id=current_head_sha,
            ),
        }

    @property
    def audit_log(self) -> tuple[ToolAuditEntry, ...]:
        return ()

    def execute(self, call: ToolCall) -> ToolResult:
        self.calls.append(call)
        if call.name == "github.pr.view":
            return ToolResult(call=call, ok=True, output={"head_sha": self.current_head_sha})
        if call.name == "github.pr.review.list":
            return ToolResult(call=call, ok=True, output=self.existing_reviews)
        return ToolResult(call=call, ok=True, output=self.outputs[call.name])


def test_output_poster_submits_official_review_separately_from_summary_comment() -> None:
    runtime = RecordingRuntime()
    poster = ToolRuntimePROutputPoster(runtime)
    comment_payload = PRCommentPayload(repo_full_name="octocat/hello-world", pr_number=7, body="summary body")
    review_payload = PRReviewPayload(
        repo_full_name="octocat/hello-world",
        pr_number=7,
        head_sha="abc123",
        body="review body",
        event="COMMENT",
        comments=(
            PRReviewComment(
                path="src/app.py",
                body="inline body",
                line=12,
                side="RIGHT",
            ),
        ),
    )

    result = poster.post_outputs(comment_payload, review_payload=review_payload, correlation_id="corr-review")

    assert result.review is not None
    assert result.review.id == 42
    assert [(call.stage, call.name) for call in runtime.calls] == [
        (WorkflowStage.OUTPUT, "github.pr.view"),
        (WorkflowStage.OUTPUT, "github.pr.review.list"),
        (WorkflowStage.OUTPUT, "github.pr.comment.create_or_update"),
        (WorkflowStage.OUTPUT, "github.pr.review.create"),
    ]
    review_call = runtime.calls[3]
    assert review_call.input == {
        "repo_full_name": "octocat/hello-world",
        "pr_number": 7,
        "head_sha": "abc123",
        "body": "review body\n\n---\n🤖 *Generated by Qaestro*\n\nCorrelation ID: `corr-review`",
        "event": "COMMENT",
        "comments": (
            {
                "path": "src/app.py",
                "body": "inline body\n\n---\n🤖 *Generated by Qaestro*",
                "line": 12,
                "side": "RIGHT",
            },
        ),
    }


def test_output_poster_rejects_stale_review_head_before_writing() -> None:
    runtime = RecordingRuntime(current_head_sha="new-head")
    poster = ToolRuntimePROutputPoster(runtime)
    payload = PRReviewPayload(
        repo_full_name="octocat/hello-world",
        pr_number=7,
        head_sha="old-head",
        body="review body",
    )

    try:
        poster.post_review(payload, correlation_id="corr-stale")
    except RuntimeError as exc:
        assert "stale head" in str(exc)
    else:  # pragma: no cover - assertion clarity
        raise AssertionError("stale review head was not rejected")

    assert [call.name for call in runtime.calls] == ["github.pr.view"]


