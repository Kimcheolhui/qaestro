def test_review_payload_degrades_unmapped_inline_comments_into_review_body() -> None:
    payload = PRReviewPayload(
        repo_full_name="octocat/hello-world",
        pr_number=7,
        head_sha="abc123",
        body="review body",
        comments=(
            PRReviewComment(path="src/app.py", body="mapped", line=12),
            PRReviewComment(path="src/missing.py", body="unmapped finding"),
        ),
    )

    prepared = payload.prepared_for_submission()

    assert len(prepared.comments) == 1
    assert prepared.comments[0].body == "mapped\n\n---\n🤖 *Generated by Qaestro*"
    assert "Unmapped inline findings" in prepared.body
    assert "src/missing.py" in prepared.body
    assert "unmapped finding" in prepared.body
    assert prepared.body.endswith("🤖 *Generated by Qaestro*")


def test_review_tool_input_normalizes_comment_payload_shape() -> None:
    raw = {
        "repo_full_name": "octocat/hello-world",
        "pr_number": 7,
        "head_sha": "abc123",
        "body": "review body",
        "event": "COMMENT",
        "comments": (
            {"path": "src/app.py", "body": "inline", "line": 12, "side": "RIGHT"},
            {"path": "src/app.py", "body": "range", "start_line": 10, "line": 12, "side": "RIGHT"},
        ),
    }

    payload = PRReviewPayload.from_tool_input(raw)

    assert payload.comments == (
        PRReviewComment(path="src/app.py", body="inline", line=12, side="RIGHT"),
        PRReviewComment(path="src/app.py", body="range", line=12, start_line=10, side="RIGHT"),
    )
    assert payload.to_client_comments() == (
        ReviewCommentInput(
            path="src/app.py",
            body="inline\n\n---\n🤖 *Generated by Qaestro*",
            line=12,
            side="RIGHT",
            start_side="RIGHT",
        ),
        ReviewCommentInput(
            path="src/app.py",
            body="range\n\n---\n🤖 *Generated by Qaestro*",
            line=12,
            side="RIGHT",
            start_line=10,
            start_side="RIGHT",
        ),
    )


