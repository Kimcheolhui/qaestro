def test_review_payload_rejects_invalid_inline_comment_shapes() -> None:
    invalid_payloads = (
        PRReviewPayload(
            repo_full_name="octocat/hello-world",
            pr_number=7,
            head_sha="abc123",
            body="review body",
            comments=(PRReviewComment(path="src/app.py", body="bad", line=0),),
        ),
        PRReviewPayload(
            repo_full_name="octocat/hello-world",
            pr_number=7,
            head_sha="abc123",
            body="review body",
            comments=(PRReviewComment(path="src/app.py", body="bad", line=12, side="LEFT"),),
        ),
        PRReviewPayload(
            repo_full_name="octocat/hello-world",
            pr_number=7,
            head_sha="abc123",
            body="review body",
            comments=(PRReviewComment(path="src/app.py", body="bad", line=12, start_line=14),),
        ),
    )

    for payload in invalid_payloads:
        try:
            payload.prepared_for_submission()
        except ValueError:
            continue
        raise AssertionError("invalid inline review comment shape was not rejected")


